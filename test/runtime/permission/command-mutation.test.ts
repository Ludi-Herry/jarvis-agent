describe('analyzeCommand — 危险 / 碰密钥的命令必须被标出（放行方向）', () => {
  it.each(DANGEROUS)('%s → %s', (cmd, expected) => {
    expect(flags(cmd)).toBe(expected);
  });
});

describe('analyzeCommand — 日常安全命令不被误拦', () => {
  it.each(SAFE)('%s → -', (cmd) => {
    expect(flags(cmd)).toBe('-');
  });
});

describe('analyzeCommand — 非字面量不能被当成空字符串放过（变异测试发现的真实缺口）', () => {
  // 修复前：`"$X"` 的字面量部分是空串，trap 把它当成 `trap '' SIG`（忽略信号）直接放行；
  // git -c 把 `core.pager=$X` 当成 `core.pager=` 去检查，也放行。实际运行时 $X 可以是任何命令。
  it.each([
    'trap "$X" EXIT',
    'trap $X EXIT',
    'trap -- "$X" EXIT',
    'trap "${X}" INT',
    'git -c "core.pager=$X" log',
    'git -c core.pager="$X" log',
    'git -c "core.sshCommand=$X" fetch',
    'git -c "alias.x=$X" x',
    'git -c "alias.x=!$X" x',
  ])('%s → danger', (cmd) => {
    expect(analyzeCommand(cmd).danger).toBe(true);
  });

  it.each([
    "trap '' EXIT",
    'trap "" EXIT',
    'trap - EXIT',
    "trap 'echo hi' EXIT",
    'git -c core.pager=cat log',
    "git -c 'alias.lg=log --oneline' lg",
    'git -c "user.name=$NAME" commit -m x',
  ])('%s → 不误拦', (cmd) => {
    expect(analyzeCommand(cmd).danger).toBe(false);
  });
});
