/**
 * `jarvis completion powershell|bash|zsh` — print a static shell completion
 * script for the jarvis command tree.
 *
 * The script is generated from one static table (below) so all three shells
 * stay in sync; a CLI e2e cross-checks the table against `jarvis --help` so
 * the table cannot silently drift from the real command tree. v1 completes
 * top-level commands, group subcommands, and global flags; per-command flags
 * stay discoverable via `--help`. The command loads no provider and reads no
 * credentials.
 *
 * Exit contract: 0 ok; 2 for an unknown shell name.
 */

export const COMPLETION_SHELLS = ['powershell', 'bash', 'zsh'] as const;
export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

export function isCompletionShell(value: string): value is CompletionShell {
  return (COMPLETION_SHELLS as readonly string[]).includes(value);
}

/** Top-level commands and group subcommands. Global flags are completed at
 * the top level; group subcommand flags are intentionally out of v1 scope. */
export const COMPLETION_GLOBAL_FLAGS = [
  '--cwd',
  '--headless',
  '--no-tui',
  '--strict-config',
  '--ignore-user-config',
  '--preset',
  '--safe',
  '--model',
  '--base-url',
  '--help',
  '--version',
] as const;

export const COMPLETION_COMMANDS: ReadonlyArray<{ name: string; subcommands?: readonly string[] }> = [
  { name: 'run' },
  { name: 'goal' },
  { name: 'loop' },
  { name: 'resume' },
  { name: 'status' },
  { name: 'doctor' },
  { name: 'sessions', subcommands: ['list', 'show', 'search', 'fork', 'rename', 'archive', 'unarchive'] },
  { name: 'checkpoints', subcommands: ['list', 'show'] },
  { name: 'rewind' },
  { name: 'review', subcommands: ['list', 'show', 'approve', 'reject'] },
  { name: 'finalize' },
  { name: 'cron', subcommands: ['run', 'daemon', 'status'] },
  { name: 'config', subcommands: ['path', 'show', 'validate', 'preset'] },
  { name: 'shadow', subcommands: ['log', 'restore'] },
  { name: 'a0', subcommands: ['run', 'report'] },
  { name: 'completion', subcommands: [...COMPLETION_SHELLS] },
];

const TOP_LEVEL = [...COMPLETION_COMMANDS.map((command) => command.name), ...COMPLETION_GLOBAL_FLAGS];

export function generateCompletionScript(shell: CompletionShell): string {
  switch (shell) {
    case 'powershell':
      return powershellScript();
    case 'bash':
      return bashScript();
    case 'zsh':
      return zshScript();
  }
}

function powershellScript(): string {
  const cases = COMPLETION_COMMANDS
    .filter((command) => command.subcommands !== undefined)
    .map((command) => `            '${command.name}' { $candidates = @(${command.subcommands!.map(quote).join(', ')}) }`)
    .join('\n');
  return `# jarvis PowerShell completion — generated by \`jarvis completion powershell\`.
# Install: append this script to your $PROFILE, or save it and dot-source it.
Register-ArgumentCompleter -Native -CommandName jarvis -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $words = @($commandAst.CommandElements | ForEach-Object { $_.Extent.Text })
    # Position of the word being completed: after a trailing space we start a
    # new (empty) word, otherwise the last element is the partial word.
    $position = if ($wordToComplete -eq '') { $words.Count } else { $words.Count - 1 }
    $candidates = @()
    if ($position -le 1) {
        $candidates = @(${TOP_LEVEL.map(quote).join(', ')})
    } elseif ($position -eq 2) {
        switch ($words[1]) {
${cases}
        }
    }
    $candidates | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}
`;
}

function bashScript(): string {
  const cases = COMPLETION_COMMANDS
    .filter((command) => command.subcommands !== undefined)
    .map((command) => `    ${command.name}) COMPREPLY=( $(compgen -W "${command.subcommands!.join(' ')}" -- "$cur") ) ;;`)
    .join('\n');
  return `# jarvis bash completion — generated by \`jarvis completion bash\`.
# Install: source this file from your ~/.bashrc, or drop it into /etc/bash_completion.d/.
_jarvis_completions() {
  local cur
  cur="\${COMP_WORDS[COMP_CWORD]}"
  COMPREPLY=()
  if [[ $COMP_CWORD -eq 1 ]]; then
    COMPREPLY=( $(compgen -W "${TOP_LEVEL.join(' ')}" -- "$cur") )
    return 0
  fi
  if [[ $COMP_CWORD -eq 2 ]]; then
    case "\${COMP_WORDS[1]}" in
${cases}
    esac
  fi
  return 0
}
complete -F _jarvis_completions jarvis
`;
}

function zshScript(): string {
  const cases = COMPLETION_COMMANDS
    .filter((command) => command.subcommands !== undefined)
    .map((command) => `        ${command.name}) compadd -- ${command.subcommands!.join(' ')} ;;`)
    .join('\n');
  return `#compdef jarvis
# jarvis zsh completion — generated by \`jarvis completion zsh\`.
# Install: save as _jarvis in a directory on your $fpath, then compinit.
_jarvis() {
  if (( CURRENT == 2 )); then
    compadd -- ${TOP_LEVEL.join(' ')}
    return
  fi
  if (( CURRENT == 3 )); then
    case "$words[2]" in
${cases}
    esac
  fi
}
compdef _jarvis jarvis
`;
}

function quote(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}
